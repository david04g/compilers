"""Sweep shapes/SRAM and compare estimated-cost decisions to exhaustive simulation."""
import argparse
from collections import Counter
import csv
import json
from pathlib import Path
import subprocess
import tempfile

from .generate import generate
from .simulator import simulate


def compile_graph(compiler, shape, hardware, tiles="8x8x8,16x16x16,16x32x16,32x16x16",
                  strategy="heuristic", placement="search"):
    compiler = str(Path(compiler).resolve())
    with tempfile.TemporaryDirectory(prefix="dataflow-") as directory:
        root = Path(directory)
        (root / "input.mlir").write_text(generate(*shape), encoding="utf-8")
        (root / "hardware.json").write_text(json.dumps(hardware), encoding="utf-8")
        options = (f"output=plan.json hardware=hardware.json tiles={tiles} strategy={strategy} "
                   f"placement={placement} emit-all=true")
        process = subprocess.run([compiler, "input.mlir", f"--dataflow-plan={options}", "-o", "planned.mlir"],
                                 cwd=root, text=True, capture_output=True, check=False)
        if not (root / "plan.json").exists():
            raise RuntimeError(f"compiler failed ({process.returncode}): {process.stderr}")
        artifact = json.loads((root / "plan.json").read_text(encoding="utf-8"))
        if process.returncode and artifact["selected_plan"] is not None:
            raise RuntimeError(f"compiler failed: {process.stderr}")
        return artifact


def compare(artifact, seed=0):
    legal = [p for p in artifact["candidates"] if p["legal"]]
    # Every candidate is numerically executed, not just the eventual winner.
    measured = {p["id"]: simulate(artifact, p, seed=seed) for p in legal}
    by_estimate = lambda p: p["estimated_cycles"]
    selected = artifact["selected_plan"]
    policies = {
        "heuristic": selected,
        "always-split": min((p for p in legal if p["mode"] == "split"), key=by_estimate, default=None),
        "always-fuse": min((p for p in legal if p["mode"] == "fused"), key=by_estimate, default=None),
        "exhaustive": min(legal, key=lambda p: measured[p["id"]]["simulated_cycles"], default=None),
    }
    optimum = measured[policies["exhaustive"]["id"]]["simulated_cycles"] if legal else None
    rows = []
    for policy, plan in policies.items():
        row = {"policy": policy, "legal": plan is not None}
        if plan:
            row.update({k: v for k, v in measured[plan["id"]].items()
                        if k not in ("timeline", "peak_bank_bytes", "resource_wait_cycles")})
            row["regret_percent"] = 100 * (row["simulated_cycles"] / optimum - 1)
        else:
            row["reason"] = "no legal candidate in this policy's candidate subset"
        rows.append(row)
    return rows


def compact_artifact(artifact):
    """Keep the runnable selection and all rejection/cost diagnostics."""
    return {**artifact, "candidates": [{k: v for k, v in c.items() if k not in ("events", "buffers")}
                                       for c in artifact["candidates"]]}


def markdown_report(rows, cases):
    lines = ["# Measured simulator results", "",
             "Generated by `python -m dataflow.experiments`; times are modeled cycles, not CPU wall time.",
             "Every legal candidate was executed against the whole-tensor NumPy reference (seed 0).",
             "Peak SRAM is the maximum reserved arena size across active regions, summed over their banks.", "",
             "| Shape M/K/N[/P] | Bytes/bank | Policy | Plan | Cycles | Off-chip bytes | Peak SRAM | Regret |",
             "|---|---:|---|---|---:|---:|---:|---:|"]
    for r in rows:
        if r["legal"]:
            lines.append(f"| {r['shape']} | {r['bank_bytes']} | {r['policy']} | {r['plan_id']} | "
                         f"{r['simulated_cycles']} | {r['offchip_bytes']} | {r['peak_sram_bytes']} | {r['regret_percent']:.1f}% |")
        else:
            lines.append(f"| {r['shape']} | {r['bank_bytes']} | {r['policy']} | illegal | — | — | — | — |")
    valid = [r for r in rows if r["policy"] == "heuristic" and r["legal"]]
    if valid:
        wins = sum(abs(r["regret_percent"]) < 1e-9 for r in valid)
        lines += ["", f"The heuristic matches the simulated optimum in {wins}/{len(valid)} cases; "
                  f"worst regret is {max(r['regret_percent'] for r in valid):.1f}%.",
                  "The exhaustive result is optimal only within these tiles, boundaries, placements, "
                  "and the fixed list scheduler. It is not a global scheduling optimum."]
    lines += ["", "## Capacity diagnostics", ""]
    for case in cases:
        lines.append(f"- {case['shape']}, {case['bank_bytes']} bytes/bank: "
                     f"{case['legal_candidates']}/{case['total_candidates']} legal. "
                     f"Example rejection: {case['example_rejection'] or 'none'}.")
    lines += ["", "## Interpretation", "",
              "Fusion removes off-chip materializations but reserves two streaming slots and can add "
              "on-chip routes. Split regions drain through DRAM before the next region starts. "
              "The heuristic uses aggregate resource load plus fill/drain cost; simulation additionally "
              "enforces dependencies, buffer-slot reuse and simultaneous resource reservations.", "",
              "Always-split and always-fuse select tiles and placements by the same analytical estimate. "
              "Always-fuse is reported as illegal when its subset has no legal candidate. "
              "The second matmul, when requested, is a separate materialized region in every policy.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compiler", type=Path, required=True)
    parser.add_argument("--hardware", type=Path, default=Path("configs/default.json"))
    parser.add_argument("--shapes", default="17x19x13,33x31x29,64x64x64,17x19x13x11",
                        help="Comma-separated MxKxN or MxKxNxP")
    parser.add_argument("--sram", default="512,1024,4096,16384", help="Comma-separated capacities in bytes per bank")
    parser.add_argument("--tiles", default="8x8x8,16x16x16,16x32x16,32x16x16")
    parser.add_argument("--output", type=Path, default=Path("out/sweep"))
    parser.add_argument("--save-plans", action="store_true", help="Save a runnable selected plan for every case")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    hw = json.loads(args.hardware.read_text(encoding="utf-8"))
    rows, cases = [], []
    for shape_text in args.shapes.split(","):
        shape = tuple(int(s) for s in shape_text.split("x"))
        if len(shape) not in (3, 4):
            parser.error("shape must be MxKxN or MxKxNxP")
        for capacity in map(int, args.sram.split(",")):
            hardware = {**hw, "bank_bytes": capacity}
            artifact = compile_graph(args.compiler, shape, hardware, args.tiles)
            report = compare(artifact)
            for r in report:
                rows.append({"shape": shape_text, "bank_bytes": capacity, **r})
            rejected = [c for c in artifact["candidates"] if not c["legal"]]
            cases.append({"shape": shape_text, "bank_bytes": capacity,
                          "legal_candidates": len(artifact["candidates"]) - len(rejected),
                          "total_candidates": len(artifact["candidates"]),
                          "example_rejection": rejected[0]["rejection"] if rejected else None})
            if args.save_plans:
                (args.output / f"{shape_text}-sram{capacity}.json").write_text(
                    json.dumps(compact_artifact(artifact), indent=2) + "\n", encoding="utf-8")
            print(f"{shape_text} SRAM={capacity}: " + ", ".join(
                f"{r['policy']}={r.get('simulated_cycles', 'illegal')}" for r in report), flush=True)
    fields = ["shape", "bank_bytes", "policy", "legal", "plan_id", "mode", "tile", "placement",
              "estimated_cycles", "simulated_cycles", "offchip_bytes", "peak_sram_bytes", "regret_percent",
              "verified", "seed", "max_abs_error", "rtol", "atol", "reason"]
    with (args.output / "sweep.csv").open("w", newline="", encoding="utf-8") as file:
        writer = csv.DictWriter(file, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    (args.output / "sweep.json").write_text(json.dumps({"rows": rows, "cases": cases,
        "hardware_base": hw, "tiles": args.tiles}, indent=2) + "\n", encoding="utf-8")
    (args.output / "report.md").write_text(markdown_report(rows, cases), encoding="utf-8")


if __name__ == "__main__":
    main()
