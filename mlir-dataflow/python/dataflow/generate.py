"""Generate the deliberately small linalg/tensor input contract (no regex parser)."""
import argparse
from pathlib import Path


def generate(m=17, k=19, n=13, p=0):
    if any(type(x) is not int or not 1 <= x <= 4096 for x in (m, k, n)) or not 0 <= p <= 4096:
        raise ValueError("dimensions must be positive integers <= 4096; p may be zero")
    a, b, c = f"tensor<{m}x{k}xf32>", f"tensor<{k}x{n}xf32>", f"tensor<{m}x{n}xf32>"
    bias = f"tensor<{n}xf32>"
    output = f"tensor<{m}x{p}xf32>" if p else c
    w2 = f", %W2: tensor<{n}x{p}xf32>" if p else ""
    text = f'''// Generated by python -m dataflow.generate. Includes explicit zero initialization.
#id = affine_map<(m, n) -> (m, n)>
#col = affine_map<(m, n) -> (n)>
module {{
  func.func @ffn(%A: {a}, %B: {b}, %bias: {bias}{w2}) -> {output} {{
    %zero = arith.constant 0.0 : f32
    %empty = tensor.empty() : {c}
    %init = linalg.fill ins(%zero : f32) outs(%empty : {c}) -> {c}
    %mm = linalg.matmul ins(%A, %B : {a}, {b}) outs(%init : {c}) -> {c}
    %biased = linalg.generic {{indexing_maps = [#id, #col, #id], iterator_types = ["parallel", "parallel"]}}
      ins(%mm, %bias : {c}, {bias}) outs(%empty : {c}) {{
      ^bb0(%x: f32, %b: f32, %unused: f32):
        %y = arith.addf %x, %b : f32
        linalg.yield %y : f32
      }} -> {c}
    %gelu = linalg.generic {{indexing_maps = [#id, #id], iterator_types = ["parallel", "parallel"]}}
      ins(%biased : {c}) outs(%empty : {c}) {{
      ^bb0(%x: f32, %unused: f32):
        %half = arith.constant 0.5 : f32
        %one = arith.constant 1.0 : f32
        %cubic = arith.constant 0.044715 : f32
        %root = arith.constant 0.7978845608028654 : f32
        %x2 = arith.mulf %x, %x : f32
        %x3 = arith.mulf %x2, %x : f32
        %scaled = arith.mulf %cubic, %x3 : f32
        %sum = arith.addf %x, %scaled : f32
        %normalized = arith.mulf %root, %sum : f32
        %t = math.tanh %normalized : f32
        %plus = arith.addf %one, %t : f32
        %half_x = arith.mulf %half, %x : f32
        %y = arith.mulf %half_x, %plus : f32
        linalg.yield %y : f32
      }} -> {c}
'''
    if p:
        text += f'''    %empty2 = tensor.empty() : {output}
    %init2 = linalg.fill ins(%zero : f32) outs(%empty2 : {output}) -> {output}
    %projected = linalg.matmul ins(%gelu, %W2 : {c}, tensor<{n}x{p}xf32>) outs(%init2 : {output}) -> {output}
    return %projected : {output}
'''
    else:
        text += f"    return %gelu : {output}\n"
    return text + "  }\n}\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name, default in (("m", 17), ("k", 19), ("n", 13), ("p", 0)):
        parser.add_argument(f"--{name}", type=int, default=default)
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(args.m, args.k, args.n, args.p), encoding="utf-8")


if __name__ == "__main__":
    main()
